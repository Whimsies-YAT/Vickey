/**
 * Auto-generate endpoint-list.ts from the endpoints/ directory
 *
 * This script eliminates manual maintenance of endpoint-list.ts.
 * Developers only need to maintain endpoint-config.json for:
 * 1. Disabled endpoints (temporarily removed)
 * 2. Path overrides (endpoint name ≠ file path)
 *
 * The endpoint-list.ts file is generated at build time and should be gitignored.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { readdir } from 'node:fs/promises';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = join(__dirname, '..');
const endpointsDir = join(rootDir, 'src/server/api/endpoints');
const configPath = join(rootDir, 'src/server/api/endpoint-config.json');
const outputPath = join(rootDir, 'src/server/api/endpoint-list.ts');

/**
 * Load configuration
 */
function loadConfig() {
	try {
		const raw = readFileSync(configPath, 'utf-8');
		const config = JSON.parse(raw);

		// Filter out comments (entries starting with _)
		return {
			disabled: (config.disabled || []).filter(x => !x.startsWith('_')),
			pathOverrides: Object.fromEntries(
				Object.entries(config.pathOverrides || {}).filter(([k]) => !k.startsWith('_')),
			),
		};
	} catch (error) {
		console.error(`[generate-endpoint-list] Error loading config: ${error.message}`);
		// No config file or parse error, use defaults silently
		return { disabled: [], pathOverrides: {} };
	}
}

/**
 * Convert file path to endpoint name
 * @param {string} filePath - Relative path from endpoints/ dir
 * @returns {string} Endpoint name
 *
 * Examples:
 *   admin/meta.ts → admin/meta
 *   notes/create.ts → notes/create
 */
function filePathToEndpointName(filePath) {
	return filePath
		.replace(/\.(ts|js)$/, '')
		.replace(/\\/g, '/');
}

/**
 * Scan endpoints directory
 */
async function scanEndpoints() {
	console.log('[generate-endpoint-list] Scanning endpoints directory...');

	const allFiles = await readdir(endpointsDir, { recursive: true });
	const files = allFiles.filter(f =>
		(f.endsWith('.ts') || f.endsWith('.js')) &&
		!f.endsWith('.d.ts') &&
		!f.endsWith('.test.ts') &&
		!f.endsWith('.spec.ts'),
	);

	console.log(`[generate-endpoint-list] Found ${files.length} endpoint files`);
	return files.sort(); // Sort for deterministic output
}

/**
 * Build endpoint map with overrides applied
 */
function buildEndpointMap(files, config) {
	const endpointMap = new Map();
	const pathToDefault = new Map();

	for (const filePath of files) {
		const defaultName = filePathToEndpointName(filePath);
		pathToDefault.set(filePath, defaultName);
		endpointMap.set(defaultName, filePath);
	}

	for (const [customName, targetPath] of Object.entries(config.pathOverrides)) {
		const normalizedPath = targetPath.replace(/\\/g, '/');

		const matchingFile = files.find(f => {
			const normalized = f.replace(/\\/g, '/');
			return normalized === normalizedPath || normalized === `${normalizedPath}.ts` || normalized === `${normalizedPath}.js`;
		});

		if (matchingFile) {
			const defaultName = pathToDefault.get(matchingFile);
			endpointMap.delete(defaultName);
			endpointMap.set(customName, matchingFile);
		} else {
			console.warn(`[generate-endpoint-list] Warning: Override target not found: ${targetPath}`);
		}
	}

	for (const disabledName of config.disabled) {
		if (endpointMap.has(disabledName)) {
			endpointMap.delete(disabledName);
		}
	}

	return endpointMap;
}

/**
 * Generate endpoint-list.ts content
 */
function generateEndpointList(endpointMap) {
	const lines = [
		'/*',
		' * SPDX-FileCopyrightText: syuilo and misskey-project',
		' * SPDX-License-Identifier: AGPL-3.0-only',
		' */',
		'',
		'/*',
		' * ⚠️ AUTO-GENERATED FILE - DO NOT EDIT MANUALLY',
		' *',
		' * This file is automatically generated by scripts/generate-endpoint-list.mjs',
		' * It should be gitignored and regenerated at build time.',
		' *',
		' * To modify endpoints, edit:',
		' *   - src/server/api/endpoint-config.json (for exclusions/overrides)',
		' *   - Add/remove files in src/server/api/endpoints/ (for new endpoints)',
		' */',
		'',
	];

	const sorted = Array.from(endpointMap.entries()).sort(([a], [b]) => a.localeCompare(b));

	for (const [endpointName, filePath] of sorted) {
		const importPath = `./endpoints/${filePath.replace(/\\/g, '/').replace(/\.ts$/, '.js')}`;
		lines.push(`export * as '${endpointName}' from '${importPath}';`);
	}

	return lines.join('\n') + '\n';
}

/**
 * Main
 */
async function main() {
	console.log('[generate-endpoint-list] ⚡ Auto-generating endpoint list\n');

	const config = loadConfig();
	console.log('[generate-endpoint-list] Configuration:');
	console.log(`  - Disabled endpoints: ${config.disabled.length}`);
	console.log(`  - Path overrides: ${Object.keys(config.pathOverrides).length}\n`);

	const files = await scanEndpoints();

	const endpointMap = buildEndpointMap(files, config);

	const content = generateEndpointList(endpointMap);

	let needsWrite = true;
	let changeReason = 'file does not exist';

	try {
		const existingContent = readFileSync(outputPath, 'utf-8');
		if (existingContent === content) {
			needsWrite = false;
			console.log('');
			console.log('[generate-endpoint-list] ✓ No changes detected');
			console.log(`  - Total files scanned: ${files.length}`);
			console.log(`  - Endpoints registered: ${endpointMap.size}`);
			console.log('  - File unchanged, skipping write\n');
		} else {
			changeReason = 'content changed';
		}
	} catch (error) {
		console.error('[generate-endpoint-list] Error reading existing file:', error);
	}

	if (needsWrite) {
		writeFileSync(outputPath, content, 'utf-8');

		const skipped = files.length - endpointMap.size;
		console.log('');
		console.log('[generate-endpoint-list] ✓ Generation complete!');
		console.log(`  - Total files scanned: ${files.length}`);
		console.log(`  - Endpoints registered: ${endpointMap.size}`);
		console.log(`  - Skipped (disabled): ${skipped}`);
		console.log(`  - Reason: ${changeReason}`);
		console.log(`\n[generate-endpoint-list] Output: ${relative(rootDir, outputPath)}\n`);
	}
}

main().catch(error => {
	console.error('[generate-endpoint-list] ❌ Error:', error);
	process.exit(1);
});
